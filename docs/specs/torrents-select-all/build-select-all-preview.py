"""Build the Torrents select-all-matching preview as one self-contained file.

The preview must be the Torrents screen itself, not a mock-up, so this inlines the panel's
real markup, styles and scripts from `src/torrentlinker/web/static`. Only the host transport
is replaced (`select-all-stub.js`) and the proposal is added on top (`select-all-preview.js`);
nothing under `src/` is read for anything but copying.

Run it again after the panel changes:

    python3 docs/specs/torrents-select-all/build-select-all-preview.py
"""

from __future__ import annotations

import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
PANEL = ROOT / "src" / "torrentlinker" / "web" / "static"

STYLES = [
    "panel/base.css",
    "torrents/view.css",
    "panel/torrent-list.css",
    "panel/file-access.css",
    "panel/toast.css",
]
# panel/transport.js is deliberately absent: the stub answers in its place.
SCRIPTS = [
    "panel/i18n.js",
    None,  # the stub, which must define TLPanel.connect before torrents/transport.js
    "panel/toast.js",
    "panel/file-access.js",
    "panel/torrent-filters.js",
    "torrents/transport.js",
    "torrents/view.js",
    "torrents/transfers.js",
    "torrents/audit.js",
    "torrents/tracker-updates.js",
]

DEMO_BAR = """    <div class="demo-bar" role="group" aria-label="Preview controls">
      <span>Aperçu</span>
      <button type="button" class="chip" id="demo-theme">Thème : sombre</button>
      <button type="button" class="chip" id="demo-lang">FR</button>
      <button type="button" class="chip" id="demo-proposal" aria-pressed="true">
        Proposition : activée
      </button>
      <span class="demo-hint" id="demo-hint"></span>
    </div>
"""


def read(path: pathlib.Path) -> str:
    return path.read_text(encoding="utf-8")


def build() -> str:
    markup = read(PANEL / "torrents" / "view.html")
    body = markup[markup.index('<main id="app">') : markup.rindex("</html>")]
    styles = "\n".join(
        f'    <style data-source="{name}">\n{read(PANEL / name)}\n    </style>' for name in STYLES
    )
    styles += f'\n    <style data-source="select-all-preview.css">\n{read(HERE / "select-all-preview.css")}\n    </style>'
    parts = []
    for name in SCRIPTS:
        source = HERE / "select-all-stub.js" if name is None else PANEL / name
        label = "select-all-stub.js" if name is None else name
        parts.append(f'    <script data-source="{label}">\n{read(source)}\n    </script>')
    parts.append(
        f'    <script data-source="select-all-preview.js">\n{read(HERE / "select-all-preview.js")}\n    </script>'
    )
    scripts = "\n".join(parts)
    return f"""<!doctype html>
<html lang="fr" data-theme="dark">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width,initial-scale=1" />
    <title>Torrents · select all matching preview</title>
    <!-- Built by build-select-all-preview.py. The markup, styles and scripts below are the
         Torrents panel's own files, copied verbatim; only the host transport is stubbed and
         the proposal is layered on top. Do not edit this file: edit the sources and rebuild. -->
{styles}
  </head>
  <body>
{DEMO_BAR}    {body}
{scripts}
  </body>
</html>
"""


if __name__ == "__main__":
    out = HERE / "select-all-prototype.html"
    out.write_text(build(), encoding="utf-8")
    print(f"{out} · {out.stat().st_size // 1024} KiB")
