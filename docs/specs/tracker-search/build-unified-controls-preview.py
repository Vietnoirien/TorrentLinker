"""Build the unified-controls preview as one self-contained file.

The preview must be the Search screen itself, not a mock-up, so this inlines the panel's
real markup, styles and scripts from `src/torrentlinker/web/static/search`. Only the host
transport is replaced (`unified-controls-stub.js`) and the control rendering is wrapped
(`unified-controls-preview.js`); nothing under `src/` is read for anything but copying.

Run it again after the panel changes:

    python3 docs/specs/tracker-search/build-unified-controls-preview.py
"""

from __future__ import annotations

import pathlib

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parents[2]
PANEL = ROOT / "src" / "torrentlinker" / "web" / "static"

STYLES = ["panel/base.css", "panel/toast.css", "search/view.css", "search/details.css"]
# panel/transport.js is deliberately absent: the stub answers in its place.
SCRIPTS = [
    "panel/i18n.js",
    "panel/toast.js",
    None,  # the stub, which must define TLPanel.connect before search/transport.js
    "search/transport.js",
    "search/release-score.js",
    "search/view.js",
    "search/results.js",
    "search/queue.js",
    "search/details.js",
]

DEMO_BAR = """    <div class="demo-bar" role="group" aria-label="Preview controls">
      <span>Aperçu</span>
      <button type="button" class="chip" id="demo-theme">Thème : sombre</button>
      <button type="button" class="chip" id="demo-lang">FR</button>
      <button type="button" class="chip" id="demo-proposal" aria-pressed="true">
        Proposition : activée
      </button>
      <span class="demo-hint" id="demo-hint"></span>
    </div>
"""


def read(path: pathlib.Path) -> str:
    return path.read_text(encoding="utf-8")


def build() -> str:
    body = read(PANEL / "search" / "view.html").split("<body>", 1)[1].rsplit("</body>", 1)[0]
    styles = "\n".join(
        f"    <style data-source=\"{name}\">\n{read(PANEL / name)}\n    </style>" for name in STYLES
    )
    styles += f'\n    <style data-source="unified-controls-preview.css">\n{read(HERE / "unified-controls-preview.css")}\n    </style>'
    parts = []
    for name in SCRIPTS:
        if name is None:
            parts.append(
                f'    <script data-source="unified-controls-stub.js">\n{read(HERE / "unified-controls-stub.js")}\n    </script>'
            )
            continue
        parts.append(f'    <script data-source="{name}">\n{read(PANEL / name)}\n    </script>')
    parts.append(
        f'    <script data-source="unified-controls-preview.js">\n{read(HERE / "unified-controls-preview.js")}\n    </script>'
    )
    scripts = "\n".join(parts)
    return f"""<!doctype html>
<html lang="fr" data-theme="dark">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width,initial-scale=1" />
    <title>Recherche · unified Tracker controls preview</title>
    <!-- Built by build-unified-controls-preview.py. The markup, styles and scripts below are
         the Search panel's own files, copied verbatim; only the host transport is stubbed and
         the control rendering is wrapped. Do not edit this file: edit the sources and rebuild. -->
{styles}
  </head>
  <body>
{DEMO_BAR}{body}
{scripts}
  </body>
</html>
"""


if __name__ == "__main__":
    out = HERE / "unified-controls-prototype.html"
    out.write_text(build(), encoding="utf-8")
    print(f"{out} · {out.stat().st_size // 1024} KiB")
